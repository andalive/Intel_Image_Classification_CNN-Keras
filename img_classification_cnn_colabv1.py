def evaluasi_detail(model, nama, dataset=test_ds, tampilkan_plot=True):
    y_true = np.concatenate([y.numpy().argmax(1) for _, y in dataset])
    y_pred = model.predict(dataset, verbose=0).argmax(1)

    print(classification_report(y_true, y_pred, target_names=class_names))

    cm = confusion_matrix(y_true, y_pred)
    if tampilkan_plot:
        plt.figure(figsize=(7, 6))
        sns.heatmap(cm, annot=True, fmt="d", cmap="Blues",
                    xticklabels=class_names, yticklabels=class_names)
        plt.xlabel("Prediction")
        plt.ylabel("Actual")
        plt.title(f"Confusion Matrix (Test) - {nama}")
        plt.show()

    return y_true, y_pred, cm

